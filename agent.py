import os
import re
from dotenv import load_dotenv
from openai import OpenAI
from gmail_service import create_draft

load_dotenv()

api_key = os.getenv("OPENAI_API_KEY")
model = os.getenv("OPENAI_MODEL", "gpt-4.1-mini")

client = OpenAI(api_key=api_key)


def email_agent(user_request):
    response = client.responses.create(
        model=model,
        instructions="""
You are a professional AI Email Agent.

Create a professional email from the user's request.

Return ONLY this format:

SUBJECT: <subject>

BODY:
<complete email>

Rules:
- Understand the user's intention.
- Create a suitable subject.
- Write a professional, natural email.
- Do not invent personal information.
- Do not include a recipient email address in the output.
""",
        input=user_request
    )

    return response.output_text


print("=" * 60)
print("                 AI EMAIL AGENT")
print("=" * 60)

# Get recipient separately
recipient = input("\nRecipient email address:\n> ").strip()

# Get any email request
user_request = input("\nWhat email do you want to create?\n> ")

print("\nGenerating email...")

result = email_agent(user_request)

# Extract subject
subject_match = re.search(
    r"SUBJECT:\s*(.+)",
    result,
    re.IGNORECASE
)

subject = (
    subject_match.group(1).strip()
    if subject_match
    else "AI Generated Email"
)

# Extract body
body_match = re.search(
    r"BODY:\s*(.*)",
    result,
    re.IGNORECASE | re.DOTALL
)

body = (
    body_match.group(1).strip()
    if body_match
    else result
)

print("\n" + "=" * 60)
print("                 GENERATED EMAIL")
print("=" * 60)

print("TO:", recipient)
print("SUBJECT:", subject)
print("\n" + body)

print("\n" + "=" * 60)
print("             SAVING TO GMAIL...")
print("=" * 60)

try:
    draft_id = create_draft(
        recipient,
        subject,
        body
    )

    print("\n" + "=" * 60)
    print("             GMAIL DRAFT CREATED")
    print("=" * 60)
    print("✓ Email generated by OpenAI")
    print("✓ Email displayed in terminal")
    print("✓ Email saved to Gmail Drafts")
    print("✓ Draft ID:", draft_id)
    print("=" * 60)

except Exception as e:
    print("\n❌ Gmail draft creation failed.")
    print("Error:", e)